// A fan of sun rays around a centre point in the XY plane of a bone.
function rays(bone, cx, cy, cz, r, n, spanDeg, size, colors, flags) {
  const out = [];
  for (let i = 0; i < n; i++) {
    const a = n === 1 ? 0 : ((i / (n - 1) - 0.5) * spanDeg * PI) / 180;
    out.push(['cone', bone, [cx + Math.sin(a) * r, cy + Math.cos(a) * r, cz], size, colors[i % colors.length], [0, 0, -a], flags || null]);
  }
  return out;
}

